/* =========================================================
   ส่วนที่ 3: ฟังก์ชันจัดการวันที่และแสดงผลคำทำนายลงใน HTML
   ========================================================= */
let currentPeriod = 'daily'; // ค่าเริ่มต้นคือ 'ดวงประจำวัน'

// ฟังก์ชันแปลงวันที่ปัจจุบันเป็นภาษาไทยตามช่วงเวลาที่เลือก
function formatDateLabel(period) {
  const today = new Date();
  if (period === 'daily') {
    return new Intl.DateTimeFormat('th-TH', {
      weekday: 'long',
      day: 'numeric',
      month: 'long',
      year: 'numeric'
    }).format(today);
  } else if (period === 'monthly') {
    return 'คำทำนายประจำเดือน' + new Intl.DateTimeFormat('th-TH', {
      month: 'long',
      year: 'numeric'
    }).format(today);
  } else {
    return 'คำทำนายประจำปี พ.ศ. ' + (today.getFullYear() + 543);
  }
}

// ฟังก์ชันหลักสำหรับอัปเดตข้อความและพื้นหลังบนหน้าจอ
function renderHoroscope() {
  const zodiacSelect = document.querySelector('#zodiacSelect');
  const zodiac = zodiacSelect ? zodiacSelect.value : 'เมษ';

  // 1. อัปเดตโหมดรูปภาพพื้นหลังที่แท็ก <body>
  document.body.dataset.bgMode = periodMeta[currentPeriod].bgMode;

  // 2. คำนวณรหัสตัวเลข (Seed) จากวันที่และชื่อราศี เพื่อให้แต่ละราศีได้คำทำนายที่จำเพาะ
  const today = new Date();
  const dayNumber = Math.floor(Date.UTC(today.getFullYear(), today.getMonth(), today.getDate()) / 86400000);
  const zodiacSeed = zodiac.charCodeAt(0) + (zodiac.charCodeAt(1) || 0);

  const list = cosmicReadings[currentPeriod];
  const index = Math.abs(dayNumber + zodiacSeed) % list.length;
  const reading = list[index];

  // 3. นำข้อมูลไปใส่ใน Element ต่างๆ ของไฟล์ daily-lucky.html
  document.querySelector('#eyebrowText').textContent = periodMeta[currentPeriod].eyebrow;
  document.querySelector('#daily-title').textContent = `${periodMeta[currentPeriod].title} • ราศี${zodiac}`;
  document.querySelector('#dailyDate').textContent = formatDateLabel(currentPeriod);

  document.querySelector('#dailyMessage').textContent = `"${reading.message}"`;
  document.querySelector('#workReading').textContent = reading.work;
  document.querySelector('#moneyReading').textContent = reading.money;
  document.querySelector('#loveReading').textContent = reading.love;

  document.querySelector('#luckyNumber').textContent = reading.number;
  document.querySelector('#luckyColor').textContent = reading.color;
  document.querySelector('#luckyFocus').textContent = reading.focus;
}

/* =========================================================
   ส่วนที่ 4: การผูกเหตุการณ์ปุ่มกด (Event Listeners) เมื่อโหลดหน้าเว็บเสร็จ
   ========================================================= */
document.addEventListener('DOMContentLoaded', () => {
  const tabButtons = document.querySelectorAll('.cosmic-tab');
  const zodiacSelect = document.querySelector('#zodiacSelect');
  const predictBtn = document.querySelector('#predictBtn');

  // เมื่อคลิกปุ่มแท็บ (ดวงประจำวัน / ดวงประจำเดือน / ดวงประจำปี)
  tabButtons.forEach((btn) => {
    btn.addEventListener('click', () => {
      tabButtons.forEach((item) => item.classList.remove('is-active'));
      btn.classList.add('is-active');
      currentPeriod = btn.dataset.period;
      renderHoroscope();
    });
  });

  // เมื่อเปลี่ยนราศีใน Dropdown หรือกดปุ่ม "เปิดคำทำนาย"
  if (zodiacSelect) {
    zodiacSelect.addEventListener('change', renderHoroscope);
  }
  if (predictBtn) {
    predictBtn.addEventListener('click', renderHoroscope);
  }

  // เรียกทำงานครั้งแรกทันทีเมื่อเปิดหน้าเว็บ
  renderHoroscope();
});