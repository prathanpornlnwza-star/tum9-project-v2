// 1. ฟังก์ชันสับไพ่ (Fisher-Yates Shuffle)
function getShuffledDeck() {
  const deck = [...tarotData];
  for (let i = deck.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [deck[i], deck[j]] = [deck[j], deck[i]];
  }
  return deck;
}

